// Real node-pty → KCoder → xterm/WebGL coverage with isolated TUI Lab ownership.
import assert from "node:assert/strict";
import fs from "node:fs/promises";
import path from "node:path";
import crypto from "node:crypto";
import { execFileSync } from "node:child_process";
import { chromium } from "../../../tools/tui-lab/node_modules/@playwright/test/index.mjs";
import { parseArgs, defaultCommandString, browserLaunchOptions } from "../../../tools/tui-lab/lib/runner-options.mjs";
import { createRunContext } from "../../../tools/tui-lab/lib/run-context.mjs";
import { defaultWorkspaceTemplate, repoRoot, runContextRuntime } from "../../../tools/tui-lab/lib/runtime-paths.mjs";
import { startSession } from "../../../tools/tui-lab/lib/session.mjs";
import { typeHumanText, waitForTerminalText } from "../../../tools/tui-lab/lib/terminal-interaction.mjs";
import { writeStartMeta, writeJsonArtifact, writeTextArtifact, writeFailureArtifacts } from "../../../tools/tui-lab/lib/runtime-artifacts.mjs";
import { attachBrowserConsole } from "../../../tools/tui-lab/lib/browser-evidence.mjs";

assert.equal(process.platform, "linux", "This acceptance entry uses Linux PTY ownership; Windows and macOS need their native host acceptance.");
const options = parseArgs(["run", "--software-webgl", "--cols", "180", "--rows", "65", ...process.argv.slice(2)], { defaultWorkspaceTemplate });
assert.ok(options.description, "Pass --description for retained terminal evidence");
options.repoRoot = repoRoot;
const sourceBinary = process.env.KCODER_MIGRATION_TUI_BINARY || path.join(repoRoot, "target/debug/kcoder");
const artifacts = await createRunContext(options, "migration-terminal", runContextRuntime());
const binary = path.join(artifacts.configHome, "owned-bin/kcoder");
await fs.mkdir(path.dirname(binary), { recursive: true, mode: 0o700 });
await fs.link(sourceBinary, binary).catch(() => fs.copyFile(sourceBinary, binary));
options.commandOverride = `exec '${binary.replaceAll("'", "'\\''")}' --cwd {workspace} tui-dev --scenario full-turn`;
const runOptions = { ...options, runDir: artifacts.dir, workspaceDir: artifacts.workspace, requestsDir: artifacts.requestsDir, configHome: artifacts.configHome };
const command = defaultCommandString(runOptions);
await writeStartMeta(artifacts, runOptions, command, "migration-terminal");
const sourceRoot = path.join(artifacts.workspace, "owned-claude");
const sourceId = crypto.randomUUID();
const jobId = crypto.randomUUID();
const continuationId = crypto.randomUUID();
const reinterpretedJobId = crypto.randomUUID(), reinterpretedContinuationId = crypto.randomUUID();
const legacyContinuationId = crypto.randomUUID();
const sourcePath = path.join(sourceRoot, "projects/project", `${sourceId}.jsonl`);
await fs.mkdir(path.dirname(sourcePath), { recursive: true, mode: 0o700 });
const original = [
  { type: "user", uuid: "a", sessionId: sourceId, version: "2.1.301", message: { role: "user", content: "TERMINAL_MIGRATION_SOURCE" } },
  { type: "assistant", uuid: "b", parentUuid: "a", sessionId: sourceId, version: "2.1.301", message: { role: "assistant", content: [{ type: "tool_use", id: "old", name: "Bash", input: { command: "touch NEVER_REPLAY_TERMINAL_HISTORY" } }] } },
  { type: "user", uuid: "c", parentUuid: "b", sessionId: sourceId, version: "2.1.301", message: { role: "user", content: [{ type: "tool_result", tool_use_id: "old", content: "Recorded old result" }] } },
].map((row) => JSON.stringify(row) + "\n").join("");
await fs.writeFile(sourcePath, original, { mode: 0o600 });
await fs.mkdir(artifacts.configDir, { recursive: true, mode: 0o700 });
await fs.writeFile(path.join(artifacts.configDir, "settings.json"), JSON.stringify({ provider: "local", local_base_url: "http://127.0.0.1:9", api_format: "openai_chat_completions", model: "fixture-model", context_window_tokens: 1000000, context_output_headroom: 10000, max_tokens: 2048 }), { mode: 0o600 });
// The helper explicitly seals a known original /3 parser fixture. An unfinished /3 job
// cannot safely guess whether its acknowledged prefix used the pre-fix or shipped fixed parser.
const fixtureBinary = process.env.KCODER_MIGRATION_FIXTURE_BINARY || path.join(repoRoot, "target/debug/examples/history_reinterpretation_fixture");
const preparedLegacy = JSON.parse(execFileSync(fixtureBinary, [artifacts.configDir, path.join(artifacts.workspace, "owned-legacy-source")], { encoding: "utf8", timeout: 30000, maxBuffer: 1024 * 1024 }));
const legacyJobId = preparedLegacy.job.jobId;
await fs.rename(preparedLegacy.sourcePath, `${preparedLegacy.sourcePath}.withheld`);
let session, browser, page;
const browserConsole = [], trace = [];
const submit = async (arguments_, expected) => {
  await page.evaluate(() => window.tuiLab.focus());
  await typeHumanText(page, `/migration ${arguments_}`);
  await page.evaluate(() => window.tuiLab.sendInput("\r"));
  await waitForTerminalText(page, expected, 60000);
  const text = await page.evaluate(() => window.tuiLab.text());
  assert.ok(!text.includes("本地迁移失败"), text);
  trace.push({ arguments: arguments_, expected });
  return text;
};
try {
  session = await startSession(runOptions);
  browser = await chromium.launch(browserLaunchOptions(options));
  page = await browser.newPage({ viewport: { width: 1700, height: 1250 } });
  attachBrowserConsole(page, browserConsole);
  await page.goto(session.url);
  await page.waitForFunction(() => window.tuiLab?.ready, null, { timeout: options.timeoutMs });
  await waitForTerminalText(page, "TUI dev mode", options.timeoutMs);
  const renderer = await page.evaluate(() => window.tuiLab.renderer);
  assert.equal(renderer, "webgl");
  await submit(`scan --source claude-code --source-root "${sourceRoot}"`, '"totalItems": 1');
  await submit(`select --source claude-code --source-root "${sourceRoot}" --source-session-id ${sourceId} --request-id ${jobId}`, '"stage": "capturing"');
  const selected = JSON.parse(await fs.readFile(path.join(artifacts.configDir, "migrations/history", `${jobId}.json`), "utf8"));
  await submit(`run --job-id ${jobId} --expected-sequence ${selected.view.sequence}`, '"stage": "normalized"');
  await submit(`text --job-id ${jobId} --record 0 --block 0`, "TERMINAL_MIGRATION_SOURCE");
  const branchText = await submit(`branch --job-id ${jobId}`, '"sealed": true');
  const viewId = branchText.match(/"viewId":\s*"([a-zA-Z0-9-]+)"/)?.[1];
  assert.ok(viewId, branchText);
  await submit(`check --job-id ${jobId} --view-id ${viewId}`, '"contextCompiled": true');
  await page.screenshot({ path: path.join(artifacts.dir, "migration-context-check.png") });
  const continued = await submit(`continue --job-id ${jobId} --view-id ${viewId} --request-id ${continuationId}`, '"stage": "imported"');
  const threadId = continued.match(/"threadId":\s*"([a-zA-Z0-9]{5})"/)?.[1];
  assert.ok(threadId, continued);
  await page.screenshot({ path: path.join(artifacts.dir, "migration-idle-imported.png") });
  // Clear only this owned empty test session's UI so an earlier imported receipt cannot satisfy the next wait.
  await typeHumanText(page, "/clear");
  await page.evaluate(() => window.tuiLab.sendInput("\r"));
  await waitForTerminalText(page, "Conversation cleared.", options.timeoutMs);
  await submit(`continuation-read --job-id ${continuationId}`, '"stage": "imported"');
  await typeHumanText(page, "/clear"); await page.evaluate(() => window.tuiLab.sendInput("\r"));
  await waitForTerminalText(page, "Conversation cleared.", options.timeoutMs);
  await submit(`page --job-id ${legacyJobId}`, '"adapterRevision": "foreign-records/3');
  const legacyBranch = await submit(`branch --job-id ${legacyJobId}`, '"sealed": true');
  const legacyViewId = legacyBranch.match(/"viewId":\s*"([a-zA-Z0-9-]+)"/)?.[1];
  assert.ok(legacyViewId, legacyBranch);
  await submit(`check --job-id ${legacyJobId} --view-id ${legacyViewId}`, '"contextCompiled": true');
  await typeHumanText(page, "/clear"); await page.evaluate(() => window.tuiLab.sendInput("\r"));
  await waitForTerminalText(page, "Conversation cleared.", options.timeoutMs);
  const legacyContinued = await submit(`continue --job-id ${legacyJobId} --view-id ${legacyViewId} --request-id ${legacyContinuationId}`, '"stage": "imported"');
  const legacyThreadId = legacyContinued.match(/"threadId":\s*"([a-zA-Z0-9]{5})"/)?.[1];
  assert.ok(legacyThreadId, legacyContinued);
  const legacyJobPath = path.join(artifacts.configDir, "migrations/history", `${legacyJobId}.json`);
  const legacyJobBytes = await fs.readFile(legacyJobPath);
  const legacyJob = JSON.parse(legacyJobBytes.toString("utf8"));
  await submit(`reinterpret preview --source-job-id ${legacyJobId}`, '"canCreate": true');
  await submit(`reinterpret create --source-job-id ${legacyJobId} --expected-source-sequence ${legacyJob.view.sequence} --request-id ${reinterpretedJobId} --confirm`, `"jobId": "${reinterpretedJobId}"`);
  await typeHumanText(page, "/clear"); await page.evaluate(() => window.tuiLab.sendInput("\r"));
  await waitForTerminalText(page, "Conversation cleared.", options.timeoutMs);
  await submit(`run --job-id ${reinterpretedJobId} --expected-sequence 0`, '"stage": "normalized"');
  await submit(`page --job-id ${reinterpretedJobId}`, '"adapterRevision": "foreign-records/4');
  await typeHumanText(page, "/clear"); await page.evaluate(() => window.tuiLab.sendInput("\r"));
  await waitForTerminalText(page, "Conversation cleared.", options.timeoutMs);
  const reinterpretBranch = await submit(`branch --job-id ${reinterpretedJobId}`, '"sealed": true');
  const reinterpretViewId = reinterpretBranch.match(/"viewId":\s*"([a-zA-Z0-9-]+)"/)?.[1];
  assert.ok(reinterpretViewId, reinterpretBranch); assert.notEqual(reinterpretViewId, legacyViewId);
  await submit(`check --job-id ${reinterpretedJobId} --view-id ${reinterpretViewId}`, '"contextCompiled": true');
  await submit(`continue --job-id ${reinterpretedJobId} --view-id ${reinterpretViewId} --request-id ${reinterpretedContinuationId}`, '"stage": "imported"');
  await typeHumanText(page, "/clear"); await page.evaluate(() => window.tuiLab.sendInput("\r"));
  await waitForTerminalText(page, "Conversation cleared.", options.timeoutMs);
  await submit(`continuation-read --job-id ${legacyContinuationId}`, `"threadId": "${legacyThreadId}"`);
  assert.deepEqual(await fs.readFile(legacyJobPath), legacyJobBytes);
  await page.screenshot({ path: path.join(artifacts.dir, "migration-reinterpreted-legacy-preserved.png") });
  await typeHumanText(page, `/resume ${legacyThreadId}`);
  await page.evaluate(() => window.tuiLab.sendInput("\r"));
  await waitForTerminalText(page, "Resumed session from", 15000);
  const resumed = await page.evaluate(() => window.tuiLab.text());
  assert.ok(!resumed.includes("TERMINAL_MIGRATION_SOURCE"), "Runtime seed must not appear as a fabricated user message");
  assert.ok(!resumed.includes("REINTERPRETED_USER_ROOT"), "The preserved /3 Runtime seed must stay outside the visible user transcript");
  await submit(`source --thread-id ${legacyThreadId}`, '"operationId"');
  await typeHumanText(page, "/clear"); await page.evaluate(() => window.tuiLab.sendInput("\r"));
  await waitForTerminalText(page, "Conversation cleared.", options.timeoutMs);
  const localSource = crypto.randomUUID(), localJob = crypto.randomUUID(), localUpload = crypto.randomUUID();
  const localSourcePath = path.join(path.dirname(sourcePath), `${localSource}.jsonl`);
  await fs.writeFile(localSourcePath, JSON.stringify({ type: "user", uuid: "local", sessionId: localSource, version: "2.1.301", message: { role: "user", content: [{ type: "document", path: "/NEVER_READ/original.pdf", media_type: "application/pdf" }] } }) + "\n", { mode: 0o600 });
  await submit(`select --source claude-code --source-root "${sourceRoot}" --source-session-id ${localSource} --request-id ${localJob}`, '"stage": "capturing"');
  await submit(`run --job-id ${localJob} --expected-sequence 0`, '"stage": "normalized"');
  await typeHumanText(page, "/clear"); await page.evaluate(() => window.tuiLab.sendInput("\r"));
  await waitForTerminalText(page, "Conversation cleared.", options.timeoutMs);
  const localBranch = await submit(`branch --job-id ${localJob}`, '"sealed": true');
  const localView = localBranch.match(/"viewId":\s*"([a-zA-Z0-9-]+)"/)?.[1];
  assert.ok(localView, localBranch);
  const localSelection = `--job-id ${localJob} --view-id ${localView} --position 0 --block 0`;
  await submit(`local-attachment prepare ${localSelection} --request-id ${localUpload}`, '"stage": "prepared"');
  const localChoice = path.join(artifacts.configDir, "explicit-cli-choice");
  await fs.mkdir(localChoice, { mode: 0o700 });
  const localChoicePath = path.join(localChoice, "supplied.txt");
  await fs.writeFile(localChoicePath, "Owned TUI supplied text\n".repeat(20000).slice(0, 400000), { mode: 0o600 });
  await submit(`local-attachment upload ${localSelection} --request-id ${localUpload} --expected-sequence 0 --file "${localChoicePath}" --confirm`, '"receivedParts": 3');
  const readLocal = () => JSON.parse(execFileSync(binary, ["migrate", "history", "--target-profile", artifacts.configDir, "local-attachment", "read", "--operation-id", localUpload], { cwd: artifacts.workspace, encoding: "utf8", timeout: 60000, maxBuffer: 1024 * 1024, env: { PATH: process.env.PATH, KCODER_CONFIG_DIR: artifacts.configDir, HOME: artifacts.configHome, USERPROFILE: artifacts.configHome, KCODER_TUI_LAB_REQUEST_DIR: artifacts.requestsDir } }));
  const uploaded = readLocal();
  assert.equal(uploaded.upload.receivedBytes, 400000);
  await fs.unlink(localChoicePath);
  await submit(`local-attachment finish --operation-id ${localUpload} --expected-sequence ${uploaded.upload.sequence}`, '"stage": "authorized"');
  const finished = readLocal();
  await submit(`local-attachment run --operation-id ${localUpload} --expected-sequence ${finished.upload.localJob.state.sequence}`, '"stage": "ready"');
  const ready = readLocal();
  assert.equal(ready.upload.localJob.historicalContentVerified, false);
  const localBinding = JSON.stringify(ready.binding);
  await submit(`check --job-id ${localJob} --view-id ${localView} --local-attachment-binding '${localBinding}' --confirm-local-attachments`, '"contextCompiled": true');
  await typeHumanText(page, "/clear"); await page.evaluate(() => window.tuiLab.sendInput("\r"));
  await waitForTerminalText(page, "Conversation cleared.", options.timeoutMs);
  await submit(`continue --job-id ${localJob} --view-id ${localView} --request-id ${crypto.randomUUID()} --local-attachment-binding '${localBinding}' --confirm-local-attachments`, '"stage": "imported"');
  assert.ok(!(await page.evaluate(() => window.tuiLab.text())).includes("Owned TUI supplied text"), "Supplemental Runtime text must remain outside the visible terminal transcript");
  await page.screenshot({ path: path.join(artifacts.dir, "migration-explicit-local-supplement.png") });
  const cancelSource = crypto.randomUUID(), cancelJob = crypto.randomUUID();
  const cancelPath = path.join(path.dirname(sourcePath), `${cancelSource}.jsonl`);
  const largeSource = Array.from({ length: 10000 }, (_, index) => JSON.stringify({ type: "user", uuid: `cancel-${index}`, sessionId: cancelSource, version: "2.1.301", message: { role: "user", content: `Owned cancel fixture ${index}` } }) + "\n").join("");
  await fs.writeFile(cancelPath, largeSource, { mode: 0o600 });
  await submit(`select --source claude-code --source-root "${sourceRoot}" --source-session-id ${cancelSource} --request-id ${cancelJob}`, '"stage": "capturing"');
  await typeHumanText(page, `/migration run --job-id ${cancelJob} --expected-sequence 0`);
  await page.evaluate(() => window.tuiLab.sendInput("\r"));
  const cancelJournal = path.join(artifacts.configDir, "migrations/history", `${cancelJob}.json`);
  const deadline = Date.now() + 15000;
  while (true) {
    const journal = JSON.parse(await fs.readFile(cancelJournal, "utf8"));
    if (journal.view.sequence > 0) break;
    assert.ok(Date.now() < deadline, "Native archive worker did not acquire its checkpoint");
    await new Promise((resolve) => setTimeout(resolve, 25));
  }
  await typeHumanText(page, "/migration stop");
  await page.evaluate(() => window.tuiLab.sendInput("\r"));
  await waitForTerminalText(page, "本地迁移命令已停止", 15000);
  assert.ok(!(await page.evaluate(() => window.tuiLab.text())).includes("本地迁移失败"), "User cancellation must not be reported as an execution failure");
  const cancelled = JSON.parse(await fs.readFile(cancelJournal, "utf8"));
  assert.equal(cancelled.view.stage, "cancelled");
  assert.equal(await fs.readFile(cancelPath, "utf8"), largeSource);
  await page.screenshot({ path: path.join(artifacts.dir, "migration-cancelled.png") });
  assert.equal(await fs.readFile(sourcePath, "utf8"), original);
  assert.equal(await fs.access(path.join(artifacts.workspace, "NEVER_REPLAY_TERMINAL_HISTORY")).then(() => true, () => false), false);
  assert.equal(await fs.access(path.join(artifacts.workspace, "NEVER_REPLAY_REINTERPRETATION")).then(() => true, () => false), false);
  const requests = await fs.readdir(artifacts.requestsDir).catch((error) => { if (error.code === "ENOENT") return []; throw error; });
  assert.equal(requests.filter((name) => name.endsWith(".json")).length, 0);
  await writeTextArtifact(path.join(artifacts.dir, "screen.txt"), await page.evaluate(() => window.tuiLab.text()));
  const assertions = { scan: true, select: true, archive: true, text: true, selectedBranch: true, contextCheck: true, idleContinuation: true, receiptReopen: true, reinterpretPreview: true, reinterpretExplicitConfirmation: true, newInterpretationRevision: true, oldJobUnchanged: true, oldPublishedContinuationRetained: true, reinterpretBranchAndIdleContinuation: true, nativeResume: true, runtimeSeedHidden: true, localUploadBytes: 400000, localUploadParts: 3, localSourceRemovedBeforeFinish: true, localBindingExplicit: true, localSupplementIdleContinuation: true, localSupplementBodyHidden: true, localHistoricalEquivalenceVerified: false, cancellationResponsive: true, cancelledAtSafeBoundary: true, sourceUnchanged: true, historicalToolsNotReplayed: true, modelRequests: 0, renderer, binarySha256: crypto.createHash("sha256").update(await fs.readFile(binary)).digest("hex"), fixtureBinarySha256: crypto.createHash("sha256").update(await fs.readFile(fixtureBinary)).digest("hex"), trace };
  await writeJsonArtifact(path.join(artifacts.dir, "assertions.json"), assertions);
  await browser.close(); browser = undefined;
  await session.stop(); await session.exitPromise;
  await writeJsonArtifact(path.join(artifacts.dir, "meta.json"), { ok: true, mode: "migration-terminal", description: options.description, ...assertions, ptyExit: session.getExitInfo(), diagnostics: session.getDiagnostics() });
  console.log(JSON.stringify({ ok: true, directory: artifacts.dir, assertions }, null, 2));
} catch (error) {
  await writeFailureArtifacts({ artifacts, runOptions, command, mode: "migration-terminal", session, page, browserConsole, trace, error });
  throw error;
} finally {
  if (browser) await browser.close();
  if (session) await session.stop();
}
