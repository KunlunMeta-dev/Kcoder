pub fn office_public_error_code(value: &str) -> Option<&'static str> {
    PUBLIC_ERRORS.iter().copied().find(|code| *code == value)
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn arbitrary_uppercase_host_data_is_not_a_public_error() {
        assert_eq!(
            office_public_error_code("OFFICE_TIMEOUT"),
            Some("OFFICE_TIMEOUT")
        );
        assert_eq!(
            office_public_error_code("OFFICE_SECRET_PRIVATE_HOST_VALUE"),
            None
        );
    }
}
