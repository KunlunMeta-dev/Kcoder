const stages = new Set(['support', 'journal', 'policy', 'targets', 'validation']);
const validationReasons = new Set(['agent_messages_invalid_response', 'agent_messages_invalid_policy',
  'agent_messages_invalid_target', 'AGENT_MESSAGES_INVALID_DISCOVERY_RESPONSE']);
function own(value, key) {
  if (value === null || typeof value !== 'object') return undefined;
  try { return Object.getOwnPropertyDescriptor(value, key)?.value; } catch { return undefined; }
}
export function closedAgentMessageReason(value) {
  return typeof value === 'string' && reasons.has(value) ? value : 'unknown';
}
export function agentMessageDiagnosticData(error) {
  const native = closedAgentMessageReason(own(own(error, 'data'), 'reason'));
  return { reason: native !== 'unknown' ? native : closedAgentMessageReason(own(error, 'message')) };
}
export function agentMessageReadDiagnostic(stage, error) {
  if (!stages.has(stage)) return undefined;
  const { reason } = agentMessageDiagnosticData(error);
  return { stage: validationReasons.has(reason) ? 'validation' : stage, reason };
}
export function isAgentMessageReadDiagnostic(value) {
  return value !== null && typeof value === 'object' && !Array.isArray(value) &&
    Object.keys(value).length === 2 && stages.has(own(value, 'stage')) &&
    typeof own(value, 'reason') === 'string' && reasons.has(own(value, 'reason'));
}
