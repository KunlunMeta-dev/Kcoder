import { build } from "esbuild";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";

const root = new URL("..", import.meta.url);
const temporaryDirectory = await mkdtemp(
  join(tmpdir(), "kcoder-terminal-webview-"),
);
try {
  await build({
    entryPoints: [new URL("src/terminal-webview/entry.ts", root).pathname],
    bundle: true,
    format: "iife",
    minify: true,
    outfile: join(temporaryDirectory, "terminal.js"),
    loader: { ".css": "css" },
  });
  const [javascript, css] = await Promise.all([
    readFile(join(temporaryDirectory, "terminal.js"), "utf8"),
    readFile(join(temporaryDirectory, "terminal.css"), "utf8"),
  ]);
  const html = `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no,viewport-fit=cover"><style>html,body,#terminal{width:100%;height:100%;margin:0;overflow:hidden;background:#101114;overscroll-behavior:none}#terminal{box-sizing:border-box;padding:8px}${css}</style></head><body><div id="terminal"></div><script>${javascript.replace(/<\/script/gi, "<\\/script")}</script></body></html>`;
  const output = `// Generated by scripts/build-terminal-webview.mjs; do not edit manually.\nexport const terminalWebViewHtml = ${JSON.stringify(html)};\n`;
  await writeFile(
    new URL("src/terminal-webview/generated-html.ts", root),
    output,
  );
} finally {
  await rm(temporaryDirectory, { recursive: true, force: true });
}
