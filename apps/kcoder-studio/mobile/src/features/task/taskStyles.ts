export function useTaskAppearance() {
  const preferences = useSyncExternalStore(subscribeAppPreferences, getAppPreferencesSnapshot, getAppPreferencesSnapshot);
  const factory = useCallback((colors: ThemeColors) => ({
    colors,
    styles: { ...createTaskStyles(colors, preferences.conversationBlockSpacing),
      ...(preferences.interfaceVersion === "classic" ? classicTaskStyles(colors) : preferences.interfaceVersion === "v3" ? v3TaskStyles(colors) : {}) },
  }), [preferences.conversationBlockSpacing, preferences.interfaceVersion]);
  return useThemedStyles(factory);
}

export function useTaskStyles() {
  return useTaskAppearance().styles;
}

export function useTaskMarkdownStyles() {
  const fontStatus = useConversationFontStatus();
  const preferences = useSyncExternalStore(
    subscribeAppPreferences,
    getAppPreferencesSnapshot,
    getAppPreferencesSnapshot,
  );
  const factory = useCallback(
    (colors: ThemeColors) => createTaskMarkdownStyles(
      colors,
      preferences.conversationFontScale,
      preferences.conversationLineSpacing,
      preferences.conversationBlockSpacing,
      preferences.conversationLetterSpacing,
      preferences.conversationFontFamily !== "system" && fontStatus === "ready" ? "Noto Sans SC" : undefined,
      preferences.conversationFontFamily !== "system" && fontStatus === "ready" ? "Noto Sans SC Bold" : undefined,
      preferences.interfaceVersion,
    ),
    [preferences.conversationFontScale, preferences.conversationLineSpacing, preferences.conversationBlockSpacing, preferences.conversationLetterSpacing, preferences.conversationFontFamily, preferences.interfaceVersion, fontStatus],
  );
  return useThemedStyles(factory);
}
