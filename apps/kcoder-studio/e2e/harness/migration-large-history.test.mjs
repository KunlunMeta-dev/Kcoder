test('process attribution includes children launched by non-main threads and rejects foreign parents', async () => {
  const context = await RunContext.create(import.meta.url, { testId: 'large-history-thread-attribution', tier: 'unit', modelPolicy: 'synthetic proc metadata only, no process or model execution' });
  let failure;
  try {
    const root = context.pathInState('proc');
    const put = async (file, text) => { await mkdir(dirname(resolve(root, file)), { recursive: true }); await writeFile(resolve(root, file), text); };
    const stat = (pid, parent) => `${pid} (owned) ${['S', String(parent), ...Array(17).fill('0'), String(pid * 100), '0'].join(' ')}`;
    for (const [pid, parent] of [[123, 1], [124, 123], [125, 123], [126, 999]]) {
      await put(`${pid}/stat`, stat(pid, parent));
      await put(`${pid}/task/${pid}/children`, '');
    }
    await put('123/task/123/children', '124');
    await put('123/task/130/children', '125');
    await put('125/task/125/children', '126');
    const tree = await linuxDescendantIdentities({ pid: 123, ppid: 1, startTicks: '12300' }, root);
    assert.deepEqual(tree.map(value => value.pid), [123, 124, 125]);
  } catch (error) { failure = error; throw error; }
  finally { await context.finish(failure ? 'failed' : 'passed', {}, failure); }
});
test('renderer snapshot binds every generated byte and rejects source links before copying', async () => {
  const context = await RunContext.create(import.meta.url, { testId: 'large-history-renderer-snapshot', tier: 'unit', modelPolicy: 'small generated renderer fixture only, no browser or model execution' });
  let failure;
  try {
    const root = context.pathInState('dist'); await mkdir(root);
    await writeFile(resolve(root, 'index.html'), '<main>owned</main>');
    const frozen = await freezeLargeHistoryRenderer(context, root, context.pathInState('snapshot'));
    await writeFile(resolve(root, 'index.html'), '<main>later build</main>');
    assert.equal(await readFile(resolve(frozen.root, 'index.html'), 'utf8'), '<main>owned</main>');
    assert.equal(frozen.files, 1);
    await symlink(resolve(root, 'index.html'), resolve(root, 'foreign-link'));
    await assert.rejects(freezeLargeHistoryRenderer(context, root, context.pathInState('rejected')), /rejects links/);
  } catch (error) { failure = error; throw error; }
  finally { await context.finish(failure ? 'failed' : 'passed', {}, failure); }
});
