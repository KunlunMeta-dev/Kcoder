import { writeLargeHistoryFixture, hashHistoryFile, parseLinuxProcessStat, parseLinuxResidentBytes,
  linuxDescendantIdentities, freezeLargeHistoryRenderer } from './migration-large-history.mjs';

test('bounded history generator preserves exact bytes, record shape and incremental digest', async () => {
  const context = await RunContext.create(import.meta.url, { testId: 'large-history-small-generator', tier: 'unit', modelPolicy: 'small artificial source only, no model or product execution' });
  let failure;
  try {
    const fixture = await writeLargeHistoryFixture(context.pathInState('claude'), context.pathInState('marker'), 64 * 1024);
    const bytes = await readFile(fixture.file);
    assert.equal(bytes.length, 64 * 1024);
    assert.equal(await hashHistoryFile(fixture.file), fixture.sha256);
    const rows = bytes.toString().trimEnd().split('\n').map(line => JSON.parse(line));
    assert.equal(rows.length, 28);
    assert.equal(rows[0].message.content, fixture.title);
    assert.equal(rows[25].message.content[0].type, 'tool_use');
    assert.equal(rows[26].message.content[0].type, 'tool_result');
    assert.equal(rows[27].message.content.length, fixture.payloadBytes);
    assert.equal(fixture.generationBufferBytes, 64 * 1024);
    await assert.rejects(readFile(context.pathInState('marker')), { code: 'ENOENT' });
  } catch (error) { failure = error; throw error; }
  finally { await context.finish(failure ? 'failed' : 'passed', {}, failure); }
});
test('Linux process metadata handles parenthesized command names and rejects incomplete measurements', () => {
  const tail = ['S', '123', ...Array(17).fill('0'), '456789', '0', '0'];
  assert.deepEqual(parseLinuxProcessStat(`42 (node (owned)) ${tail.join(' ')}`), { pid: 42, ppid: 123, startTicks: '456789' });
  assert.deepEqual(parseLinuxResidentBytes('VmRSS:\t123 kB\nVmHWM: 456 kB\n'), { rss: 123 * 1024, hwm: 456 * 1024 });
  assert.throws(() => parseLinuxProcessStat('42 (bad) S 123'));
  assert.throws(() => parseLinuxResidentBytes('VmRSS: 123 kB\n'));
});
