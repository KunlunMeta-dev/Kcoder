import { budgetIndexedDbFixture } from '../../../../shared/migrationResourceBudgetIndexedDbFixture.mjs'
import { fireEvent, render, screen, waitFor, cleanup } from '@testing-library/react'
import { beforeEach, afterEach, expect, it, vi } from 'vitest'
import { OwnedBudgetPanel } from './MigrationResourceBudgetPanel'
const { api } = vi.hoisted(() => ({ api: { resourcesRead: vi.fn(), resourcesIncrease: vi.fn() } }))
vi.mock('@/kcoder/gatewayMigration', () => ({ createMigrationApi: () => api }))
vi.mock('@/hooks/useTranslation', () => ({ useTranslation: () => ({ t: (key: string) => key }) }))
const limits = { maxTotalBytes: 1024, maxPayloadFiles: 1, minFreeBytes: 1048576, minFreeFileNodes: 0 }
const view = (revision = 0, chosen = limits, requestedReceipt?: object) => ({ phase: 'active', jobId: 'mig-owned', limits: chosen, policyRevision: revision, usage: { reservedBytes: 0, committedBytes: 0, reservedFiles: 0, committedFiles: 0 }, ...(requestedReceipt ? { requestedReceipt } : {}) })
const props = { deviceId: 'target', workspacePath: '/owned', scope: 'account-target-mount', jobId: 'mig-owned', planId: 'plan-owned', status: 'completed_with_issues', unresolvedActions: 1, isCurrent: () => true }
beforeEach(() => { vi.resetAllMocks(); window.localStorage.clear(); vi.stubGlobal('indexedDB', budgetIndexedDbFixture().indexedDB); api.resourcesRead.mockResolvedValue(view()) })
afterEach(() => { cleanup(); vi.unstubAllGlobals() })
async function edit() {
  await screen.findByTestId('migration-resource-budget')
  fireEvent.change(screen.getByTestId('migration-resource-bytes'), { target: { value: '2048' } })
  fireEvent.change(screen.getByTestId('migration-resource-files'), { target: { value: '2' } })
  fireEvent.click(screen.getByTestId('migration-resource-increase'))
  fireEvent.change(screen.getByTestId('migration-resource-confirm-input'), { target: { value: 'INCREASE' } })
}
it('only reads on mount, requires explicit confirmation, and never resumes the batch after a receipt', async () => {
  api.resourcesIncrease.mockImplementation(async intent => { const receipt = { jobId: intent.jobId, requestId: intent.requestId, previousRevision: 0, revision: 1, limits: intent.limits }; api.resourcesRead.mockResolvedValue(view(3, { ...intent.limits, maxTotalBytes: 8192 }, receipt)); return receipt })
  render(<OwnedBudgetPanel {...props}/>); await edit(); expect(api.resourcesIncrease).not.toHaveBeenCalled()
  fireEvent.click(screen.getByTestId('migration-resource-confirm'))
  await screen.findByTestId('migration-resource-receipt')
  expect(api.resourcesIncrease).toHaveBeenCalledTimes(1)
  expect(api.resourcesRead).toHaveBeenLastCalledWith(expect.objectContaining({ requestId: api.resourcesIncrease.mock.calls[0][0].requestId }))
  expect(screen.getByTestId('migration-resource-current').textContent).toContain('current')
  expect(api.resourcesIncrease.mock.calls[0][0].limits).toEqual({ ...limits, maxTotalBytes: 2048, maxPayloadFiles: 2 })
})
it('hides an old capability without an increase and keeps other read failures actionable', async () => {
  api.resourcesRead.mockRejectedValue(new Error('migration_resource_budget_update_required'))
  const result = render(<OwnedBudgetPanel {...props}/>); await waitFor(() => expect(api.resourcesRead).toHaveBeenCalledTimes(1))
  expect(screen.queryByTestId('migration-resource-budget')).toBeNull(); result.unmount()
  api.resourcesRead.mockRejectedValue(new Error('offline')); render(<OwnedBudgetPanel {...props}/>)
  await screen.findByRole('alert'); expect(screen.getByTestId('migration-resource-read')).not.toBeDisabled(); expect(api.resourcesIncrease).not.toHaveBeenCalled()
})
it('invalidates confirmation when the batch becomes cancelled; completed groups stay readable', async () => {
  const result = render(<OwnedBudgetPanel {...props}/>); await edit()
  result.rerender(<OwnedBudgetPanel {...props} status="cancel_requested"/>)
  expect(screen.getByTestId('migration-resource-confirm')).toBeDisabled(); fireEvent.click(screen.getByTestId('migration-resource-confirm')); expect(api.resourcesIncrease).not.toHaveBeenCalled()
  result.rerender(<OwnedBudgetPanel {...props} status="rolled_back"/>)
  expect(screen.getByTestId('migration-resource-increase')).toBeDisabled(); expect(screen.getByTestId('migration-resource-read')).not.toBeDisabled()
})
it('persists a lost reply, reopens with reads only and resubmits only the original full intent after confirmation', async () => {
  api.resourcesIncrease.mockRejectedValue(new Error('transport lost'))
  const result = render(<OwnedBudgetPanel {...props}/>); await edit(); fireEvent.click(screen.getByTestId('migration-resource-confirm'))
  await screen.findByRole('alert'); const original = structuredClone(api.resourcesIncrease.mock.calls[0][0]); result.unmount()
  render(<OwnedBudgetPanel {...props}/>); await waitFor(() => expect(screen.getByTestId('migration-resource-resubmit')).not.toBeDisabled())
  expect(api.resourcesIncrease).toHaveBeenCalledTimes(1)
  fireEvent.click(screen.getByTestId('migration-resource-resubmit')); fireEvent.change(screen.getByTestId('migration-resource-confirm-input'), { target: { value: 'INCREASE' } }); fireEvent.click(screen.getByTestId('migration-resource-confirm'))
  await waitFor(() => expect(api.resourcesIncrease).toHaveBeenCalledTimes(2)); expect(api.resourcesIncrease.mock.calls[1][0]).toEqual(original)
})

it('only a higher original-group revision without this receipt allows explicit local archival and a separately confirmed new request', async () => {
  api.resourcesIncrease.mockRejectedValue(new Error('original response unknown'))
  render(<OwnedBudgetPanel {...props}/>); await edit(); fireEvent.click(screen.getByTestId('migration-resource-confirm'))
  await screen.findByRole('alert'); const original = structuredClone(api.resourcesIncrease.mock.calls[0][0])
  fireEvent.click(screen.getByTestId('migration-resource-read'))
  await waitFor(() => expect(screen.getByTestId('migration-resource-resubmit')).not.toBeDisabled())
  expect(screen.queryByTestId('migration-resource-archive-expired')).toBeNull()
  api.resourcesRead.mockResolvedValue({ ...view(1), limits: { ...limits, maxPayloadFiles: 3 } })
  fireEvent.click(screen.getByTestId('migration-resource-read'))
  await screen.findByTestId('migration-resource-expired'); expect(screen.queryByTestId('migration-resource-resubmit')).toBeNull()
  fireEvent.click(screen.getByTestId('migration-resource-archive-expired'))
  fireEvent.change(screen.getByTestId('migration-resource-confirm-input'), { target: { value: 'ARCHIVE' } }); fireEvent.click(screen.getByTestId('migration-resource-confirm'))
  await screen.findByTestId('migration-resource-expired-history'); expect(api.resourcesIncrease).toHaveBeenCalledTimes(1)
  fireEvent.change(screen.getByTestId('migration-resource-bytes'), { target: { value: '4096' } })
  fireEvent.change(screen.getByTestId('migration-resource-files'), { target: { value: '4' } })
  fireEvent.click(screen.getByTestId('migration-resource-increase')); expect(api.resourcesIncrease).toHaveBeenCalledTimes(1)
  fireEvent.change(screen.getByTestId('migration-resource-confirm-input'), { target: { value: 'INCREASE' } }); fireEvent.click(screen.getByTestId('migration-resource-confirm'))
  await waitFor(() => expect(api.resourcesIncrease).toHaveBeenCalledTimes(2))
  expect(api.resourcesIncrease.mock.calls[1][0].expectedPolicyRevision).toBe(1)
  expect(api.resourcesIncrease.mock.calls[1][0].requestId).not.toBe(original.requestId)
})
it('invalidates a queued metadata intent before dispatch when the target/job scope changes', async () => {
  api.resourcesRead.mockImplementation(async ({ jobId }) => ({ ...view(), jobId }))
  const result = render(<OwnedBudgetPanel {...props}/>); await edit(); fireEvent.click(screen.getByTestId('migration-resource-confirm'))
  result.rerender(<OwnedBudgetPanel {...props} deviceId="other-target" scope="other-account-target" jobId="mig-new" planId="plan-new"/>)
  await waitFor(() => expect(api.resourcesRead).toHaveBeenCalledWith(expect.objectContaining({ jobId: 'mig-new' }), expect.anything()))
  expect(api.resourcesIncrease).not.toHaveBeenCalled()
  expect(screen.queryByTestId('migration-resource-pending')).toBeNull()
})
it('keeps completed budgets read-only until a verified original attachment observation is supplied', async () => {
  const result = render(<OwnedBudgetPanel {...props} status="completed"/>); await screen.findByTestId('migration-resource-bytes')
  expect(screen.getByTestId('migration-resource-bytes')).toBeDisabled()
  result.rerender(<OwnedBudgetPanel {...props} status="completed" completedBudgetVerified/> )
  expect(screen.getByTestId('migration-resource-bytes')).not.toBeDisabled()
  expect(api.resourcesIncrease).not.toHaveBeenCalled()
})
