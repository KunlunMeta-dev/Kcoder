test('UI-only fixture: a failed Weixin status read replaces the stale waiting label and recovers the same QR flow', async ({ page }) => {
  await page.goto('/e2e/fixtures/channel-actions.html?authNetworkFailure=1')
  await revealConnections(page)
  await page.getByTestId('channel-add-connection').click()
  await page.getByTestId('channel-add-connection-weixin').click()
  const authentication = page.getByTestId('channel-initial-authentication')
  const image = authentication.getByRole('img', { name: /用微信扫描二维码/ })
  await expect(authentication.getByRole('status')).toHaveText('暂时无法查询认证状态')
  await expect(authentication.getByRole('alert')).toContainText('连接微信服务失败')
  await expect(authentication.getByRole('alert')).toContainText('WEIXIN_QR_NETWORK_UNAVAILABLE')
  await expect(image).toBeVisible()
  await expect(page.getByRole('dialog').getByRole('button', { name: '保 存', exact: true })).toHaveCount(0)
  const calls = await page.evaluate(() => window.__channelActions.calls())
  const original = calls.find(row => row.action === 'authorization_poll')!.flowId!
  expect(calls.filter(row => row.action === 'authorization_poll')).toEqual([{ action: 'authorization_poll', id: original, flowId: original }])
  await page.evaluate(() => window.__channelActions.scan('weixin'))
  await authentication.getByRole('button', { name: '核对原操作' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByTestId('channel-connection-instance')).toHaveCount(3)
  const recovered = await page.evaluate(() => window.__channelActions.calls())
  // StrictMode may replay Begin; it must retain one flow, and recovery must not register another.
  expect(recovered.filter(row => row.action === 'authorization_begin')).toHaveLength(calls.filter(row => row.action === 'authorization_begin').length)
  expect(recovered.filter(row => row.action.startsWith('authorization_')).every(row => row.flowId === original)).toBe(true)
  expect(recovered.filter(row => row.action === 'authorization_commit')).toHaveLength(1)
})


