test('UI-only fixture: a late saved configuration cannot close or overwrite a peer editor', async ({ page }) => {
  await page.goto('/e2e/fixtures/channel-actions.html?controlled=1&editable=1')
  await revealConnections(page)
  const rows = page.getByTestId('channel-connection-instance')
  await rows.first().getByRole('button', { name: '配 置' }).click()
  await page.getByRole('textbox', { name: '名称' }).fill('已提交配置')
  await page.getByRole('dialog').getByRole('button', { name: '保 存', exact: true }).click()
  await expect.poll(() => page.evaluate(() => window.__channelActions.pending())).toEqual(['feishu-1'])
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await rows.last().getByRole('button', { name: '配 置' }).click()
  await page.getByRole('textbox', { name: '名称' }).fill('另一个未保存草稿')
  await page.evaluate(() => window.__channelActions.finish('feishu-1', true))
  await expect(page.getByRole('textbox', { name: '名称' })).toHaveValue('另一个未保存草稿')
  await expect(page.getByRole('dialog')).toBeVisible()
})

