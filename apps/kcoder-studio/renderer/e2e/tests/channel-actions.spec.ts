import { expect, test, type Page } from '@playwright/test'

async function revealConnections(page: Page) {
  for (const group of await page.getByTestId('channel-platform-group').all()) {
    await group.locator(':scope > summary').click()
    for (const row of await group.getByTestId('channel-connection-instance').all()) await row.locator(':scope > summary').click()
  }
}


test('UI-only fixture: a legacy workspace binding is visible and rebinds only the selected chat after review', async ({ page }, testInfo) => {
  await page.goto('/e2e/fixtures/channel-actions.html?chats=1&legacyBinding=1')
  await revealConnections(page)
  await page.getByTestId('channel-connection-instance').first().getByRole('button', { name: /聊天与绑定/ }).click()
  const row = page.getByTestId('channel-chat-row').filter({ hasText: '开发联调群' })
  await expect(row).toContainText('绑定工作区不匹配')
  await expect(row).toContainText('可能是旧工作区留下的绑定')
  await expect(row).toContainText('/Users/Admin/Projects/Alpha')
  await expect(row.getByRole('button', { name: '打开会话' })).toBeDisabled()
  await page.screenshot({ path: testInfo.outputPath('legacy-workspace-binding.png'), fullPage: true })
  await row.getByRole('button', { name: '重新绑定', exact: true }).click()
  const choose = page.getByTestId('channel-rebind-dialog')
  await choose.getByRole('combobox', { name: '新的绑定会话' }).selectOption(JSON.stringify(['macmini', '/Users/Admin/Projects/Current', 'replacement-session']))
  await choose.getByRole('button', { name: '核对绑定' }).click()
  const review = page.getByTestId('task-channel-binding-dialog')
  await expect(review).toContainText('当前工作区会话')
  await expect(review.getByRole('radio')).toBeChecked()
  await page.screenshot({ path: testInfo.outputPath('review-replacement-task.png'), fullPage: true })
  await review.getByRole('button', { name: '绑定通道', exact: true }).click()
  expect(await page.evaluate(() => window.__channelActions.calls().filter(row => row.action === 'bind'))).toHaveLength(0)
  await review.getByRole('button', { name: '确认', exact: true }).click()
  await expect(review).toHaveCount(0)
  await expect(row).toContainText('当前工作区会话')
  await expect(row).not.toContainText('绑定工作区不匹配')
  const inventory = await page.evaluate(async () => (await fetch('/api/channels')).json())
  expect(inventory.chats.find((chat: { id: string }) => chat.id === 'chat-1').binding.target).toEqual({ serverId: 'macmini', workspacePath: '/Users/Admin/Projects/Current', threadId: 'replacement-session' })
  expect(inventory.chats.find((chat: { id: string }) => chat.id === 'chat-0').binding).toBeNull()
  expect(await page.evaluate(() => window.__channelActions.calls().filter(row => row.action === 'bind'))).toHaveLength(1)
})

