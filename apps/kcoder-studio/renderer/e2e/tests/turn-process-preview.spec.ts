import { test, expect } from '@playwright/test'
import { readFile, writeFile } from 'node:fs/promises'

test('captures actual process summaries and their disclosure states (model-independent)', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize({ width: 1040, height: 900 })
  await page.goto('/e2e/fixtures/turn-process-preview.html')
  const preview = page.getByTestId('process-preview')
  const toggle = preview.getByTestId('final-processing-toggle')
  await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  await expect(preview.getByTestId('message-assistant')).toHaveCount(2)
  const captures: Array<[string, string]> = []
  async function capture(name: string, label: string) {
    const path = testInfo.outputPath(name + '.png')
    await page.screenshot({ path, fullPage: true, animations: 'disabled' })
    captures.push([label, (await readFile(path)).toString('base64')])
  }
  await capture('completed-collapsed', '完成后收起')
  await toggle.click()
  await expect(preview.getByTestId('turn-process-content')).toHaveCount(2)
  await expect(preview.getByTestId('message-assistant')).toHaveCount(3)
  await expect(preview.getByTestId('assistant-thinking-toggle').first()).toHaveAttribute('aria-expanded', 'false')
  await expect(preview.getByTestId('assistant-thinking-content')).toHaveCount(0)
  await expect(preview.locator('[data-tool-detail-toggle]').first()).toHaveAttribute('aria-expanded', 'false')
  const sources = preview.getByTestId('native-web-sources-toggle')
  await expect(sources).toHaveAttribute('aria-expanded', 'false')
  await expect(preview.getByRole('link')).toHaveCount(0)
  await sources.click()
  await expect(sources).toHaveAttribute('aria-expanded', 'true')
  await expect(preview.getByRole('link')).toHaveCount(1)
  await expect(preview.getByTestId('assistant-thinking-toggle').first()).toHaveAttribute('aria-expanded', 'false')
  await expect(preview.locator('[data-tool-detail-toggle]').first()).toHaveAttribute('aria-expanded', 'false')
  await sources.click()
  await capture('completed-expanded', '展开外层，思考、工具详情和来源仍收起')
  await toggle.click()
  await page.getByRole('button', { name: '运行中', exact: true }).click()
  await expect(toggle).toBeEnabled()
  await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  await expect(preview.getByTestId('turn-process-content')).toHaveCount(0)
  await toggle.click()
  await expect(preview.getByTestId('turn-process-content')).toHaveCount(2)
  await expect(sources).toHaveAttribute('aria-expanded', 'false')
  await expect(preview.getByTestId('assistant-thinking-toggle').first()).toHaveAttribute('aria-expanded', 'false')
  await capture('running', '运行中')
  await page.getByRole('button', { name: '已完成', exact: true }).click()
  await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  await toggle.click()
  await expect(preview.getByTestId('turn-process-content')).toHaveCount(2)
  await page.getByRole('button', { name: '运行中', exact: true }).click()
  await page.getByRole('button', { name: '工具失败', exact: true }).click()
  await expect(toggle).toBeEnabled()
  await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  await expect(toggle).toContainText('有步骤失败')
  await expect(preview.getByText('部分目录读取失败', { exact: false })).toBeVisible()
  await capture('tool-failed-collapsed', '工具失败后收起，状态与回复仍可见')
  await toggle.click()
  await expect(preview.getByTestId('turn-process-content')).toHaveCount(2)
  await capture('tool-failed-expanded', '手动展开失败详情')
  await page.getByRole('button', { name: '运行中', exact: true }).click()
  await page.getByRole('button', { name: '已停止', exact: true }).click()
  await expect(toggle).toContainText('已停止')
  await expect(toggle).toBeEnabled()
  await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  await toggle.click()
  await expect(preview.locator('.animate-spin')).toHaveCount(0)
  await expect(preview.getByText(/未记录结果|结果未记录/)).toBeVisible()
  await capture('stopped', '停止后结果未记录')
  expect(errors).toEqual([])
  const html = '<!doctype html><html lang="zh-CN"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>KCoder 当前对话展示</title><body style="margin:24px;font-family:system-ui;background:#f6f7f8"><h1>KCoder 当前对话展示</h1><p>来自当前 MessageList 组件的浏览器截图，使用示例数据。点击标题查看各状态。</p>' + captures.map(([label, data]) => `<details open style="margin:24px 0"><summary style="cursor:pointer;font-size:20px">${label}</summary><img alt="${label}" style="display:block;max-width:100%;margin-top:12px;border:1px solid #ddd" src="data:image/png;base64,${data}"></details>`).join('') + '</body></html>'
  await writeFile(testInfo.outputPath('current-process-preview.html'), html)
})
