import { expect, test } from '@playwright/test'

for (const width of [1280, 390]) test(`process clock advances through slow or failed calibration (${width}px, UI-only)`, async ({ page }) => {
  await page.setViewportSize({ width, height: 800 })
  const time = new Date('2026-11-22T00:00:00Z')
  await page.clock.install({ time })
  await page.clock.pauseAt(new Date(time.getTime() + 1000))
  await page.goto('/e2e/fixtures/process-clock-connection.html')
  const elapsed = page.getByTestId('turn-process-elapsed')
  await expect(elapsed).toHaveText('10秒')
  await page.getByTestId('clock-toggle').click()
  await page.clock.runFor(5000)
  await expect(elapsed).toHaveText('10秒')
  await page.getByTestId('clock-toggle').click()
  await expect(page.getByTestId('clock-read-count')).toHaveText('2')
  await expect(elapsed).toHaveText('15秒')
  await page.clock.runFor(5000)
  await expect(elapsed).toHaveText('20秒')
  await page.getByTestId('clock-fail').click()
  await page.clock.runFor(3000)
  await expect(elapsed).toHaveText('23秒')
  await page.getByTestId('clock-toggle').click()
  await page.clock.runFor(2000)
  await page.getByTestId('clock-toggle').click()
  await expect(page.getByTestId('clock-read-count')).toHaveText('3')
  await expect(elapsed).toHaveText('25秒')
  await page.getByTestId('clock-older').click()
  await expect(elapsed).toHaveText('25秒')
  await page.clock.runFor(1000)
  await expect(elapsed).toHaveText('26秒')
  await page.getByTestId('clock-finish').click()
  await page.clock.runFor(10_000)
  await expect(elapsed).toHaveText('42秒')
  await expect(page.getByTestId('turn-process-status')).toHaveText('已完成')
  await expect(page.getByTestId('clock-read-count')).toHaveText('3')
})
