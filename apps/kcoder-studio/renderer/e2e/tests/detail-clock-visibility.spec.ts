import { expect, test, type Page } from '@playwright/test'

async function openClocks(page: Page) {
  const time = new Date('2026-11-22T00:00:00Z')
  await page.clock.install({ time })
  await page.clock.pauseAt(new Date(time.getTime() + 1000))
  await page.goto('/e2e/fixtures/reference-panels.html?panel=detail-clocks', { waitUntil: 'domcontentloaded' })
  await page.getByTestId('fixture-detail-clocks').waitFor({ state: 'visible', timeout: 30_000 })
}

test('retry countdown pauses while retained and returns at its original elapsed deadline (UI-only)', async ({ page }, testInfo) => {
  await openClocks(page)
  const retry = page.getByTestId('provider-retry-status')
  await expect(retry).toHaveAttribute('data-state', 'waiting')
  await page.getByTestId('provider-retry-details-toggle').click()
  await page.getByTestId('fixture-clock-toggle').click()
  const frozen = await retry.textContent()
  await page.clock.runFor(20_000)
  expect(await retry.textContent()).toBe(frozen)
  await page.getByTestId('fixture-clock-toggle').click()
  await expect(retry).toHaveAttribute('data-state', 'retrying')
  await expect(page.getByTestId('provider-retry-details-toggle')).toHaveAttribute('aria-expanded', 'true')
  const expired = await retry.textContent()
  await page.clock.runFor(10_000)
  expect(await retry.textContent()).toBe(expired)
  await page.screenshot({ path: testInfo.outputPath('retry-countdown-return.png'), animations: 'disabled' })
})

test('sidebar and Wiki clocks catch up on retained return; collapsed sidebars stay quiet (UI-only)', async ({ page }, testInfo) => {
  await openClocks(page)
  const sidebar = page.getByTestId('fixture-sidebar-time')
  const wiki = page.getByTestId('wiki-job-status')
  await expect(sidebar).toHaveText('1m')
  await expect(wiki).toContainText('0分钟')
  await page.getByTestId('fixture-clock-toggle').click()
  const previousWiki = await wiki.textContent()
  await page.clock.runFor(120_000)
  expect(await sidebar.textContent()).toBe('1m')
  expect(await wiki.textContent()).toBe(previousWiki)
  await page.getByTestId('fixture-clock-toggle').click()
  await expect(sidebar).toHaveText('3m')
  await expect(wiki).toContainText('2分钟')
  await page.getByTestId('fixture-sidebar-toggle').click()
  await page.clock.runFor(60_000)
  expect(await sidebar.textContent()).toBe('3m')
  await expect(wiki).toContainText('3分钟')
  await page.getByTestId('fixture-sidebar-toggle').click()
  await expect(sidebar).toHaveText('4m')
  await page.getByTestId('fixture-clock-finish').click()
  await expect(wiki).not.toContainText('分钟')
  await page.screenshot({ path: testInfo.outputPath('sidebar-wiki-clocks.png'), animations: 'disabled' })
})

for (const width of [1280, 390]) test(`local detail clocks pause retained rendering and preserve hidden completion (${width}px, UI-only)`, async ({ page }, testInfo) => {
  await page.setViewportSize({ width, height: 800 })
  await openClocks(page)
  const tool = page.getByTestId('tool-block-duration')
  const thinking = page.getByTestId('thinking-duration')
  const summary = page.getByTestId('processing-summary-header')
  const goal = page.getByTestId('goal-status-bar')
  await expect(tool).toHaveText('0.0s')
  await page.clock.runFor(1200)
  await expect(tool).toHaveText('1.2s')
  await expect(thinking).toContainText('1')
  await expect(summary).toContainText('1 秒')
  await expect(goal).toContainText('1s')
  await page.getByTestId('fixture-clock-toggle').click()
  await expect(page.getByTestId('fixture-detail-clocks')).toBeHidden()
  const frozenTool = await tool.textContent(), frozenThinking = await thinking.textContent(), frozenSummary = await summary.textContent()
  const frozenGoal = await goal.textContent()
  await page.clock.runFor(5000)
  await expect(tool).toHaveCount(1)
  await expect(thinking).toHaveCount(1)
  expect(await tool.textContent()).toBe(frozenTool)
  expect(await thinking.textContent()).toBe(frozenThinking)
  expect(await summary.textContent()).toBe(frozenSummary)
  expect(await goal.textContent()).toBe(frozenGoal)
  await page.getByTestId('fixture-clock-toggle').click()
  await expect(page.getByTestId('fixture-detail-clocks')).toBeVisible()
  await expect(tool).toHaveText('6.2s')
  await expect(thinking).toContainText('6')
  await expect(summary).toContainText('6 秒')
  await expect(goal).toContainText('6s')
  await page.getByTestId('fixture-clock-toggle').click()
  await page.clock.runFor(1300)
  await page.getByTestId('fixture-clock-finish').click()
  await expect(tool).toHaveText('7.5s')
  await expect(thinking).toContainText('7')
  await expect(goal).toContainText('7s')
  await page.getByTestId('fixture-clock-toggle').click()
  const completedTool = await tool.textContent(), completedThinking = await thinking.textContent(), completedSummary = await summary.textContent()
  const completedGoal = await goal.textContent()
  await page.clock.runFor(10_000)
  expect(await tool.textContent()).toBe(completedTool)
  expect(await thinking.textContent()).toBe(completedThinking)
  expect(await summary.textContent()).toBe(completedSummary)
  expect(await goal.textContent()).toBe(completedGoal)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('detail-clocks-completed.png'), animations: 'disabled' })
})
