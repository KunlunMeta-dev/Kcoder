test('PATH and NODE_PATH are appended so system Node and existing entries keep priority', () => {
  const runtime = { binDirectory: '/data/skill-runtime/bin', nodeModules: '/opt/studio/resources/skill-runtime/node_modules' };
  const base = { PATH: '/usr/local/bin:/usr/bin', NODE_PATH: '/project/lib', HOME: '/home/u' };
  const env = composeSkillNodeEnvironment(base, runtime, 'linux');
  assert.equal(env.PATH, '/usr/local/bin:/usr/bin:/data/skill-runtime/bin');
  assert.equal(env.NODE_PATH, '/project/lib:/opt/studio/resources/skill-runtime/node_modules');
  assert.equal(base.PATH, '/usr/local/bin:/usr/bin', 'input environment is not mutated');
  assert.deepEqual(composeSkillNodeEnvironment(env, runtime, 'linux'), env, 'composition is idempotent');
  assert.equal(composeSkillNodeEnvironment({}, runtime, 'linux').NODE_PATH, runtime.nodeModules);
  assert.equal(composeSkillNodeEnvironment({ PATH: '/bin' }, { binDirectory: null, nodeModules: runtime.nodeModules }, 'linux').PATH, '/bin');

  const windows = composeSkillNodeEnvironment({ Path: 'C:\\Windows\\system32;C:\\Program Files\\nodejs;' },
    { binDirectory: 'C:\\Users\\dev\\AppData\\Roaming\\KCoder Studio\\skill-runtime\\bin', nodeModules: 'C:\\Program Files\\KCoder Studio\\resources\\skill-runtime\\node_modules' }, 'win32');
  assert.deepEqual(Object.keys(windows).sort(), ['NODE_PATH', 'Path']);
  assert.equal(windows.Path, 'C:\\Windows\\system32;C:\\Program Files\\nodejs;C:\\Users\\dev\\AppData\\Roaming\\KCoder Studio\\skill-runtime\\bin');
  assert.equal(windows.NODE_PATH, 'C:\\Program Files\\KCoder Studio\\resources\\skill-runtime\\node_modules');
});

