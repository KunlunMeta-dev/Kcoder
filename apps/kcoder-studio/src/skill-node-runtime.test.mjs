test('launchers are rewritten atomically when the executable changes and kept when unchanged', posixOnly, async t => {
  const root = await scratch(t);
  const nodeModules = await fakeTree(root);
  const directory = join(root, 'data', 'skill-runtime', 'bin');
  const first = skillLauncherFiles({ executable: '/opt/KCoder Studio 1/kcoder-studio', directory, nodeModules,
    launchers: [PLAYWRIGHT], platform: 'linux' }).files;
  assert.deepEqual((await writeSkillLaunchers({ directory, files: first, platform: 'linux' })).written, ['node', 'playwright-mcp']);
  const before = await stat(join(directory, 'node'));
  assert.equal(before.mode & 0o777, 0o755);

  const again = await writeSkillLaunchers({ directory, files: first, platform: 'linux' });
  assert.deepEqual(again.written, []);
  assert.deepEqual(again.unchanged, ['node', 'playwright-mcp']);
  assert.equal((await stat(join(directory, 'node'))).ino, before.ino, 'unchanged launchers are not rewritten');

  const updated = skillLauncherFiles({ executable: '/opt/KCoder Studio 2/kcoder-studio', directory, nodeModules, platform: 'linux' }).files;
  const result = await writeSkillLaunchers({ directory, files: updated, platform: 'linux' });
  assert.deepEqual(result.written, ['node']);
  assert.deepEqual(result.removed, ['playwright-mcp'], 'a launcher whose bundled script is gone is removed');
  const after = await stat(join(directory, 'node'));
  assert.notEqual(after.ino, before.ino, 'replacement is a rename of a new file');
  assert.match(await readFile(join(directory, 'node'), 'utf8'), /exec '\/opt\/KCoder Studio 2\/kcoder-studio' "\$@"/);
  assert.deepEqual(await readdir(directory), ['node'], 'no temporary files remain');

  await writeFile(join(directory, 'unrelated'), 'keep');
  await writeSkillLaunchers({ directory, files: [], platform: 'linux' });
  assert.deepEqual(await readdir(directory), ['unrelated'], 'only owned launcher names are removed');
});

