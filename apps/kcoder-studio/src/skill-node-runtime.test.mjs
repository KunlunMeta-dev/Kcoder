test('lark-cli alone still yields a runtime; links and non-executable files are refused', posixOnly, async t => {
  const root = await scratch(t);
  const larkCli = await fakeLarkCli(join(root, 'lark cli 工具'));
  const runtime = await prepareSkillNodeRuntime({ env: { KCODER_STUDIO_SKILL_NODE_MODULES: join(root, 'absent', 'node_modules'), KCODER_STUDIO_LARK_CLI_DIR: larkCli },
    gatewayRoot: root, dataDirectory: 'relative', warn: () => {} });
  assert.equal(runtime.binDirectory, null);
  assert.equal(runtime.nodeModules, null);
  assert.equal(runtime.larkCliDirectory, larkCli);

  const { symlink } = await import('node:fs/promises');
  const linked = join(root, 'linked');
  await symlink(larkCli, linked);
  const plain = await fakeLarkCli(join(root, 'plain'), { mode: 0o644 });
  const linkedBinary = join(root, 'linked-binary');
  await mkdir(linkedBinary);
  await symlink(join(larkCli, 'lark-cli'), join(linkedBinary, 'lark-cli'));
  for (const directory of [linked, plain, linkedBinary]) {
    const warnings = [];
    const refused = await prepareSkillNodeRuntime({ env: { KCODER_STUDIO_SKILL_NODE_MODULES: join(root, 'absent', 'node_modules'), KCODER_STUDIO_LARK_CLI_DIR: directory },
      gatewayRoot: root, dataDirectory: join(root, 'data'), warn: message => warnings.push(message) });
    assert.equal(refused.larkCliDirectory, null, directory);
    assert.match(warnings[0], /no executable lark-cli/);
  }
});
