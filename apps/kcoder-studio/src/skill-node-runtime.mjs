// Local skill Node runtime: launchers that reuse the Gateway's own executable
// (Electron with ELECTRON_RUN_AS_NODE=1 in packaged Studio), the shipped,
// pinned skill package tree and the official lark-cli binary. Only local
// same-account targets receive it.
import { randomUUID } from 'node:crypto';
import { chmod, lstat, mkdir, readFile, rename, rm, stat, writeFile } from 'node:fs/promises';
import { posix, win32 } from 'node:path';

/** Bundled command-line packages exposed as launchers next to `node`. */
export const SKILL_RUNTIME_LAUNCHERS = Object.freeze([
  Object.freeze({ name: 'playwright-mcp', packageName: '@playwright/mcp', script: '@playwright/mcp/cli.js' }),
]);

// Launchers no longer generated. They stay owned so that a launcher written by
// an earlier development build is removed instead of lingering on PATH.
const RETIRED_LAUNCHER_NAMES = Object.freeze(['lark-mcp']);
const OWNED_LAUNCHER_NAMES = Object.freeze(['node', ...SKILL_RUNTIME_LAUNCHERS.map(entry => entry.name), ...RETIRED_LAUNCHER_NAMES]);

/** Directory of the packaged official lark-cli, beside `gateway` in resources. */
export const LARK_CLI_DIRECTORY_NAME = 'lark-cli';

export function larkCliExecutableName(platform = process.platform) {
  return platform === 'win32' ? 'lark-cli.exe' : 'lark-cli';
}
const CONTROL_CHARACTERS = /[\x00-\x1f\x7f]/;

function pathsFor(platform) {
  return platform === 'win32' ? win32 : posix;
}

/** Quote one argument for POSIX sh. Single quotes disable every expansion. */
export function posixShellQuote(value) {
  if (typeof value !== 'string' || value.length === 0 || CONTROL_CHARACTERS.test(value)) {
    throw new Error('Skill runtime launcher path is not representable');
  }
  return `'${value.replaceAll("'", `'\\''`)}'`;
}

/** POSIX sh launcher: exec replaces the shell, so stdio and exit status pass through. */
export function posixLauncherScript({ executable, script, platform = process.platform }) {
  // Git Bash on Windows accepts drive paths with forward slashes.
  const portable = value => (platform === 'win32' ? value.replaceAll('\\', '/') : value);
  const argv = [executable, ...(script ? [script] : [])].map(value => posixShellQuote(portable(value)));
  return [
    '#!/bin/sh',
    '# Generated by KCoder Studio. Rewritten when the Studio executable changes.',
    'ELECTRON_RUN_AS_NODE=1',
    'export ELECTRON_RUN_AS_NODE',
    `exec ${argv.join(' ')} "$@"`,
    '',
  ].join('\n');
}

/**
 * Express a path for a .cmd file. cmd.exe decodes batch bytes with the active
 * console code page, so only ASCII text is embedded. A non-ASCII prefix shared
 * with the launcher directory (typically the user profile) is reached through
 * `%~dp0`, which cmd expands from its Unicode state.
 */
export function windowsBatchPath(target, launcherDirectory) {
  const safe = value => typeof value === 'string' && value.length > 0 && !CONTROL_CHARACTERS.test(value)
    && !value.includes('"') && /^[\x20-\x7e]*$/.test(value);
  if (!win32.isAbsolute(target) || !win32.isAbsolute(launcherDirectory)) return null;
  const absolute = win32.resolve(target);
  if (safe(absolute)) return absolute.replaceAll('%', '%%');
  const relative = win32.relative(win32.resolve(launcherDirectory), absolute);
  if (win32.isAbsolute(relative) || !safe(relative)) return null;
  return `%~dp0${relative.replaceAll('%', '%%')}`;
}

/** Windows batch launcher, or null when a path cannot be represented safely. */
export function windowsLauncherScript({ executable, script, launcherDirectory }) {
  const argv = [executable, ...(script ? [script] : [])].map(value => windowsBatchPath(value, launcherDirectory));
  if (argv.some(value => value === null)) return null;
  return [
    '@echo off',
    'rem Generated by KCoder Studio. Rewritten when the Studio executable changes.',
    'setlocal DisableDelayedExpansion',
    'set "ELECTRON_RUN_AS_NODE=1"',
    `${argv.map(value => `"${value}"`).join(' ')} %*`,
    'exit /b %ERRORLEVEL%',
    '',
  ].join('\r\n');
}

/** Describe every launcher file; callers decide which scripts actually exist. */
export function skillLauncherFiles({ executable, directory, nodeModules, launchers = [], platform = process.platform }) {
  const paths = pathsFor(platform);
  const entries = [{ name: 'node' }, ...launchers.map(entry => ({ name: entry.name, script: paths.join(nodeModules, ...entry.script.split('/')) }))];
  const files = [];
  const unavailable = [];
  for (const entry of entries) {
    files.push({ name: entry.name, content: posixLauncherScript({ executable, script: entry.script, platform }) });
    if (platform !== 'win32') continue;
    const batch = windowsLauncherScript({ executable, script: entry.script, launcherDirectory: directory });
    if (batch === null) unavailable.push(`${entry.name}.cmd`);
    else files.push({ name: `${entry.name}.cmd`, content: batch });
  }
  return { files, unavailable };
}

function ownedNames(platform) {
  return OWNED_LAUNCHER_NAMES.flatMap(name => (platform === 'win32' ? [name, `${name}.cmd`] : [name]));
}

async function verifyLauncherDirectory(path) {
  const info = await lstat(path);
  if (!info.isDirectory() || info.isSymbolicLink()) throw new Error('Skill runtime launcher directory is not an ordinary directory');
}

async function currentContent(path, platform) {
  try {
    const info = await lstat(path);
    if (!info.isFile() || info.isSymbolicLink()) return null;
    if (platform !== 'win32' && (info.mode & 0o111) === 0) return null;
    return await readFile(path, 'utf8');
  } catch (error) {
    if (error.code === 'ENOENT') return null;
    throw error;
  }
}

/**
 * Converge the owned launcher directory to `files`. Unchanged launchers are
 * not rewritten; changed ones are replaced by an atomic rename, and stale
 * owned launchers (for example a removed package) are deleted. Files with
 * other names are never touched.
 */
export async function writeSkillLaunchers({ directory, files, platform = process.platform }) {
  const paths = pathsFor(platform);
  await mkdir(paths.dirname(directory), { recursive: true });
  await verifyLauncherDirectory(paths.dirname(directory));
  await mkdir(directory, { recursive: true });
  await verifyLauncherDirectory(directory);
  const written = [];
  const unchanged = [];
  for (const file of files) {
    if (!ownedNames(platform).includes(file.name)) throw new Error('Unknown skill runtime launcher');
    const path = paths.join(directory, file.name);
    if (await currentContent(path, platform) === file.content) {
      unchanged.push(file.name);
      continue;
    }
    const temporary = paths.join(directory, `.${file.name}.${randomUUID()}.tmp`);
    try {
      await writeFile(temporary, file.content, { flag: 'wx' });
      await chmod(temporary, 0o755);
      await rename(temporary, path);
    } finally {
      await rm(temporary, { force: true }).catch(() => {});
    }
    written.push(file.name);
  }
  const removed = [];
  const wanted = new Set(files.map(file => file.name));
  for (const name of ownedNames(platform)) {
    if (wanted.has(name)) continue;
    const path = paths.join(directory, name);
    try {
      const info = await lstat(path);
      if (!info.isFile() && !info.isSymbolicLink()) continue;
      await rm(path, { force: true });
      removed.push(name);
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
    }
  }
  return { written, unchanged, removed };
}

function environmentKey(env, name, platform) {
  if (platform !== 'win32') return name;
  if (Object.hasOwn(env, name)) return name;
  return Object.keys(env).find(key => key.toUpperCase() === name) ?? name;
}

function appendSearchEntry(env, name, entry, platform) {
  const delimiter = platform === 'win32' ? ';' : ':';
  const key = environmentKey(env, name, platform);
  const current = typeof env[key] === 'string' ? env[key] : '';
  const entries = current.split(delimiter).filter(Boolean);
  const same = value => (platform === 'win32' ? value.toLowerCase() === entry.toLowerCase() : value === entry);
  if (entries.some(same)) return;
  env[key] = [...entries, entry].join(delimiter);
}

/** True only for targets whose app-server runs as the Gateway's own account. */
export function providesSkillNodeRuntime(target) {
  return target?.transport === 'local' && !target.security;
}

/**
 * Compose a child environment. Existing PATH and NODE_PATH entries keep
 * priority, so an installed system Node, lark-cli and project packages win.
 * The bundled lark-cli directory follows the launcher directory.
 */
export function composeSkillNodeEnvironment(env, runtime, platform = process.platform) {
  const next = { ...env };
  if (runtime?.binDirectory) appendSearchEntry(next, 'PATH', runtime.binDirectory, platform);
  if (runtime?.larkCliDirectory) appendSearchEntry(next, 'PATH', runtime.larkCliDirectory, platform);
  if (runtime?.nodeModules) appendSearchEntry(next, 'NODE_PATH', runtime.nodeModules, platform);
  return next;
}

/** Apply the prepared runtime to a local same-account app-server only. */
export function skillNodeEnvironmentForTarget(runtime, target, env, platform = process.platform) {
  if (!runtime || !providesSkillNodeRuntime(target)) return env;
  return composeSkillNodeEnvironment(env, runtime, platform);
}

async function isDirectory(path) {
  try {
    const info = await lstat(path);
    return info.isDirectory() && !info.isSymbolicLink();
  } catch (error) {
    if (error.code === 'ENOENT') return false;
    throw error;
  }
}

async function isFile(path, { follow = false } = {}) {
  try {
    const info = follow ? await stat(path) : await lstat(path);
    return info.isFile() && !info.isSymbolicLink();
  } catch (error) {
    if (error.code === 'ENOENT' || error.code === 'ENOTDIR') return false;
    throw error;
  }
}

/** Packaged resources/skill-runtime first, then the source-tree install. */
export function skillNodeModulesCandidates({ env = process.env, gatewayRoot, platform = process.platform }) {
  const paths = pathsFor(platform);
  const configured = env.KCODER_STUDIO_SKILL_NODE_MODULES;
  if (typeof configured === 'string' && configured !== '') {
    if (!paths.isAbsolute(configured)) throw new Error('KCODER_STUDIO_SKILL_NODE_MODULES must be an absolute path');
    return [paths.resolve(configured)];
  }
  return [
    paths.resolve(gatewayRoot, '..', 'skill-runtime', 'node_modules'),
    paths.resolve(gatewayRoot, 'skill-runtime', 'node_modules'),
  ];
}

/**
 * Packaged resources/lark-cli, or an explicit KCODER_STUDIO_LARK_CLI_DIR.
 * Source checkouts have no default copy; prepare one with
 * scripts/release/prepare-lark-cli.mjs and point the variable at it.
 */
export function larkCliDirectoryCandidates({ env = process.env, gatewayRoot, platform = process.platform }) {
  const paths = pathsFor(platform);
  const configured = env.KCODER_STUDIO_LARK_CLI_DIR;
  if (typeof configured === 'string' && configured !== '') {
    if (!paths.isAbsolute(configured)) throw new Error('KCODER_STUDIO_LARK_CLI_DIR must be an absolute path');
    return { configured: true, candidates: [paths.resolve(configured)] };
  }
  return { configured: false, candidates: [paths.resolve(gatewayRoot, '..', LARK_CLI_DIRECTORY_NAME)] };
}

/** An ordinary directory holding a regular, executable lark-cli binary. */
async function usableLarkCliDirectory(directory, platform) {
  if (!await isDirectory(directory)) return false;
  const paths = pathsFor(platform);
  let info;
  try { info = await lstat(paths.join(directory, larkCliExecutableName(platform))); }
  catch (error) { if (error.code === 'ENOENT' || error.code === 'ENOTDIR') return false; throw error; }
  if (!info.isFile() || info.isSymbolicLink()) return false;
  return platform === 'win32' || (info.mode & 0o111) !== 0;
}

/**
 * Prepare the local skill runtime once at Gateway startup. It never throws:
 * a missing or unusable runtime produces one warning and no environment
 * change, so app-server launch is unaffected.
 */
export async function prepareSkillNodeRuntime({
  env = process.env, gatewayRoot, dataDirectory, executable = process.execPath,
  platform = process.platform, warn = message => console.warn(message),
} = {}) {
  const problems = [];
  let nodeModules = null;
  let binDirectory = null;
  let larkCliDirectory = null;
  let launchers = [];
  try {
    for (const candidate of skillNodeModulesCandidates({ env, gatewayRoot, platform })) {
      if (await isDirectory(candidate)) { nodeModules = candidate; break; }
    }
    if (!nodeModules) problems.push('skill package tree not found');
  } catch (error) {
    problems.push(error.message);
  }
  try {
    const paths = pathsFor(platform);
    if (typeof dataDirectory !== 'string' || !paths.isAbsolute(dataDirectory)) throw new Error('Gateway data directory is unavailable');
    if (typeof executable !== 'string' || !paths.isAbsolute(executable) || !await isFile(executable, { follow: true })) throw new Error('Gateway executable is unavailable');
    const directory = paths.join(dataDirectory, 'skill-runtime', 'bin');
    const available = [];
    if (nodeModules) {
      for (const launcher of SKILL_RUNTIME_LAUNCHERS) {
        if (await isFile(paths.join(nodeModules, ...launcher.script.split('/')))) available.push(launcher);
      }
    }
    const { files, unavailable } = skillLauncherFiles({ executable, directory, nodeModules, launchers: available, platform });
    if (unavailable.length) problems.push(`launcher path is not representable for ${unavailable.join(', ')}`);
    await writeSkillLaunchers({ directory, files, platform });
    binDirectory = directory;
    launchers = files.map(file => file.name);
  } catch (error) {
    problems.push(error.message);
  }
  try {
    const { configured, candidates } = larkCliDirectoryCandidates({ env, gatewayRoot, platform });
    for (const candidate of candidates) {
      if (await usableLarkCliDirectory(candidate, platform)) { larkCliDirectory = candidate; break; }
    }
    // Only an explicit setting is worth a warning; source checkouts ship no copy.
    if (!larkCliDirectory && configured) problems.push('configured lark-cli directory has no executable lark-cli');
  } catch (error) {
    problems.push(error.message);
  }
  if (problems.length) warn(`KCoder Studio skill Node runtime is partially unavailable: ${problems.join('; ')}`);
  if (!binDirectory && !nodeModules && !larkCliDirectory) return null;
  return Object.freeze({ binDirectory, nodeModules, larkCliDirectory, launchers: Object.freeze(launchers) });
}
